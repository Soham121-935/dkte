/** Domain-specific small components: data-source tags, mode badges, confidence labels, actuator chips. */
import type { ReactNode } from 'react';
import { Activity, Beaker, CircleHelp, Eye, Flame, Fan, Droplets, BookOpen, Cpu, TrendingUp, WifiOff } from 'lucide-react';
import { Badge, type Tone } from '@/components/ui';
import { fmtAgo, fmtDateTime, sourceLabel } from '@/lib/format';
import { cn } from '@/lib/utils';
import type { Actuator, ActuatorEntry, ConnectionStatus, Quality } from '@/api/types';

/* ----------------------------------------------------- Data source tags */
export type DataKind = 'measured' | 'simulated' | 'predicted' | 'observed' | 'reference' | 'user' | 'general' | 'historical';

const KIND_META: Record<DataKind, { label: string; tone: Tone; icon: typeof Activity; title: string }> = {
  measured: { label: 'Measured', tone: 'brand', icon: Activity, title: 'Measured by a physical sensor on the device' },
  historical: { label: 'Historical', tone: 'teal', icon: Activity, title: 'Stored sensor history' },
  simulated: { label: 'Simulated', tone: 'amber', icon: Beaker, title: 'Generated by the hardware simulator – not a real measurement' },
  predicted: { label: 'Predicted', tone: 'info', icon: TrendingUp, title: 'Model output with uncertainty – not a measurement' },
  observed: { label: 'User-observed', tone: 'teal', icon: Eye, title: 'Entered by a grower from visual inspection' },
  reference: { label: 'Reference', tone: 'neutral', icon: BookOpen, title: 'Reference value from general cultivation literature – verify for your strain' },
  user: { label: 'User-entered', tone: 'teal', icon: Eye, title: 'Entered by a user' },
  general: { label: 'General knowledge', tone: 'muted', icon: CircleHelp, title: 'General knowledge, not specific to your data' },
};

export function kindFromSource(source: string | null | undefined): DataKind {
  switch (source) {
    case 'hardware':
      return 'measured';
    case 'simulation':
      return 'simulated';
    case 'manual':
    case 'user':
    case 'profile_user':
    case 'batch_override':
      return 'user';
    case 'reference':
    case 'profile_reference':
    case 'defaults':
      return 'reference';
    case 'predicted':
    case 'model':
      return 'predicted';
    case 'observed':
      return 'observed';
    default:
      return 'general';
  }
}

export function SourceTag({ kind, source, className, compact }: { kind?: DataKind; source?: string | null; className?: string; compact?: boolean }) {
  const k = kind ?? kindFromSource(source);
  const meta = KIND_META[k];
  const Icon = meta.icon;
  return (
    <Badge tone={meta.tone} title={source && !kind ? `${meta.title} (${sourceLabel(source)})` : meta.title} className={className}>
      <Icon className="h-3 w-3" aria-hidden />
      {!compact && meta.label}
    </Badge>
  );
}

/* --------------------------------------------------- Connection / mode */
export function ConnectionBadge({ status, lastSeen, className }: { status: ConnectionStatus | string; lastSeen?: string | null; className?: string }) {
  const tone: Tone = status === 'online' ? 'brand' : status === 'stale' ? 'amber' : status === 'offline' ? 'danger' : 'neutral';
  const label = status === 'offline' ? 'DISCONNECTED' : status.toUpperCase();
  return (
    <Badge tone={tone} dot className={className} title={lastSeen ? `Last seen ${fmtDateTime(lastSeen)} (${fmtAgo(lastSeen)})` : undefined}>
      {status === 'offline' && <WifiOff className="h-3 w-3" aria-hidden />}
      {label}
    </Badge>
  );
}

export function ModeBadge({ mode, label, className, large }: { mode: string; label?: string; className?: string; large?: boolean }) {
  const tone: Tone = mode === 'live' ? 'brand' : mode === 'demo' ? 'amber' : 'danger';
  const text = label ?? (mode === 'live' ? 'LIVE' : mode === 'demo' ? 'DEMO MODE' : 'DISCONNECTED');
  return (
    <Badge tone={tone} dot className={cn(large && 'px-2 py-1 text-xs', className)}>
      {mode === 'demo' && <Beaker className="h-3 w-3" aria-hidden />}
      {mode === 'disconnected' && <WifiOff className="h-3 w-3" aria-hidden />}
      {text}
    </Badge>
  );
}

export function QualityBadge({ quality }: { quality: Quality | undefined }) {
  if (!quality || quality === 'ok') return null;
  const tone: Tone = quality === 'missing' ? 'neutral' : 'danger';
  return (
    <Badge tone={tone} title={`Reading quality: ${quality}`}>
      {quality.replace(/_/g, ' ')}
    </Badge>
  );
}

export function ConfidenceTag({ level, basis, className }: { level: string | undefined; basis?: string[] | string | null; className?: string }) {
  if (!level) return null;
  const tone: Tone = level === 'high' ? 'brand' : level === 'medium' ? 'teal' : level === 'low' ? 'amber' : 'neutral';
  const basisText = Array.isArray(basis) ? basis.filter(Boolean).join('; ') : basis ?? '';
  return (
    <Badge tone={tone} className={className} title={basisText ? `Basis: ${basisText} (qualitative – not a calibrated probability)` : 'Qualitative confidence – not a calibrated probability'}>
      confidence: {level}
    </Badge>
  );
}

/* ------------------------------------------------------------ Actuators */
export const ACTUATOR_META: Record<Actuator, { label: string; icon: typeof Fan; hardware: string }> = {
  fan: { label: 'Fan', icon: Fan, hardware: '12 V DC fan (fresh-air exchange / cooling towards ambient)' },
  heater: { label: 'Heater', icon: Flame, hardware: 'Tungsten bulb via relay (requires independent thermal cutoff)' },
  humidifier: { label: 'Humidifier', icon: Droplets, hardware: 'USB ultrasonic humidifier via driver PCB' },
};

export function actuatorStatusTone(entry: ActuatorEntry | undefined): Tone {
  const st = entry?.status;
  if (st === 'confirmed') return 'brand';
  if (st === 'pending') return 'amber';
  if (st === 'mismatch') return 'danger';
  return 'neutral';
}

export function ActuatorChip({ actuator, entry, reported, className }: { actuator: Actuator; entry?: ActuatorEntry; reported?: boolean | null; className?: string }) {
  const meta = ACTUATOR_META[actuator];
  const Icon = meta.icon;
  const confirmed = entry?.confirmed ?? reported ?? null;
  const status = entry?.status ?? (confirmed === null ? 'unknown' : 'confirmed');
  const on = confirmed === true;
  return (
    <div className={cn('flex items-center gap-2 rounded-md border border-line bg-surface-2 px-2.5 py-1.5', className)} title={entry?.last_reason ?? undefined}>
      <Icon className={cn('h-4 w-4', on ? 'text-brand' : 'text-ink-3')} aria-hidden />
      <div className="min-w-0 flex-1 leading-tight">
        <div className="text-xs font-medium text-ink">{meta.label}</div>
        <div className="text-[11px] text-ink-3">
          {confirmed === null ? 'state unknown' : on ? 'ON' : 'OFF'}
          {entry?.requested !== undefined && entry?.requested !== null && entry.requested !== confirmed && <span className="text-amber"> · requested {entry.requested ? 'ON' : 'OFF'}</span>}
        </div>
      </div>
      <Badge tone={status === 'confirmed' ? 'brand' : status === 'pending' ? 'amber' : status === 'mismatch' ? 'danger' : 'neutral'} title={ACTUATOR_STATUS_HELP[status] ?? undefined}>
        {status}
      </Badge>
    </div>
  );
}

/** Plain-language meaning of the actuator status words (shown as tooltips). */
export const ACTUATOR_STATUS_HELP: Record<string, string> = {
  confirmed: 'The chamber has confirmed this state',
  pending: 'A command was sent; waiting for the chamber to confirm',
  mismatch: 'The chamber reports a different state than requested – check the wiring or relay',
  unknown: 'No report from the chamber yet',
};

export function DeviceKindIcon({ kind, className }: { kind: string; className?: string }) {
  return kind === 'simulated' ? <Beaker className={cn('h-4 w-4 text-amber', className)} aria-label="Simulated device" /> : <Cpu className={cn('h-4 w-4 text-brand', className)} aria-label="Hardware device" />;
}

export function SectionTitle({ title, description, actions }: { title: string; description?: ReactNode; actions?: ReactNode }) {
  return (
    <div className="mb-4 flex flex-wrap items-start justify-between gap-3">
      <div>
        <h1 className="text-lg font-semibold text-ink">{title}</h1>
        {description && <p className="mt-0.5 max-w-3xl text-xs text-ink-3">{description}</p>}
      </div>
      {actions && <div className="flex flex-wrap items-center gap-2">{actions}</div>}
    </div>
  );
}

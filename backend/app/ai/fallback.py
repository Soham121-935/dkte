"""Deterministic assistant used when the AI provider is unavailable.

It answers the common operational questions directly from the assembled
context, so the dashboard stays useful without an API key.  Replies are
clearly labelled as deterministic (not generated by a language model).
"""
from __future__ import annotations

import re
from typing import Any

from .insight import build_briefing

FALLBACK_LABEL = "_Answered directly from your stored data – the AI language model is offline right now (deterministic assistant)._"


def _dt(iso: str | None) -> str:
    if not iso:
        return "unknown time"
    return iso.replace("T", " ")[:16] + " UTC"


def _reading_header(ctx: dict[str, Any]) -> str:
    cr = ctx.get("current_reading")
    if not cr:
        return "No readings are stored for this device."
    label = "**Simulated** reading" if cr["source"] == "simulation" else "Measured reading"
    stale = " ⚠️ stale" if cr["stale"] else ""
    return f"{label} at {_dt(cr['measured_at'])}{stale}"


def answer(question: str, ctx: dict[str, Any]) -> str:
    q = question.lower()
    cr = ctx.get("current_reading")
    tg = ctx.get("targets", {})
    parts: list[str] = []

    def in_range(value: float | None, lo: Any, hi: Any) -> str:
        if value is None or lo is None or hi is None:
            return "unknown"
        return "inside" if float(lo) <= value <= float(hi) else ("below" if value < float(lo) else "above")

    if re.search(r"\b(how is|how's|hows|everything|all good|okay|ok|status|summary|overview|doing|briefing|look)\b", q) and not re.search(r"\b(temperature|temp|humidity|heater|fan|humidifier|stage)\b", q):
        briefing = build_briefing(ctx)
        parts.append(f"**{briefing['headline']}**")
        parts.extend(f"- {p['text']}" for p in briefing["points"])
        parts.append(f"**Next step:** {briefing['next_step']}")
    if re.search(r"\b(temperature|temp|warm|cold|hot)\b", q):
        if cr:
            status = in_range(cr["temperature_c"], tg.get("temperature_min_c"), tg.get("temperature_max_c"))
            parts.append(f"{_reading_header(ctx)}: temperature **{cr['temperature_c']} °C** – {status} the configured range "
                         f"{tg.get('temperature_min_c')}–{tg.get('temperature_max_c')} °C ({tg.get('source_label')}).")
        else:
            parts.append(_reading_header(ctx))
    if re.search(r"\b(humidity|rh|moist)\b", q):
        if cr:
            status = in_range(cr["relative_humidity_percent"], tg.get("humidity_min_percent"), tg.get("humidity_max_percent"))
            parts.append(f"{_reading_header(ctx)}: relative humidity **{cr['relative_humidity_percent']} %** – {status} the configured range "
                         f"{tg.get('humidity_min_percent')}–{tg.get('humidity_max_percent')} %.")
            if "moist" in q:
                parts.append(f"Growing-medium moisture: **{cr['substrate_moisture_raw']}** (raw, uncalibrated ADC units).")
        else:
            parts.append(_reading_header(ctx))
    if re.search(r"\b(changed|change|last 24|yesterday|today|trend)\b", q) and not re.search(r"\b(problem|issue|alert|anomal|wrong|error)\b", q):
        h = ctx.get("history", {})
        c = h.get("change_24h")
        if c:
            parts.append(f"**Last 24 h (historical {'/'.join(h.get('sources', []))} data, {h.get('n_readings')} readings):** since {_dt(c['from'])} temperature changed "
                         f"{c['temperature_delta_c']:+} °C, humidity {c['humidity_delta_percent']:+} %, moisture {c['moisture_delta_raw']:+} raw.")
            for m, label in (("temperature_c", "Temperature"), ("relative_humidity_percent", "Humidity")):
                if m in h:
                    parts.append(f"- {label}: min {h[m]['min']}, max {h[m]['max']}, mean {h[m]['mean']}")
            rt = h.get("actuator_runtime") or {}
            if rt:
                parts.append("- Actuator on-time: " + ", ".join(f"{k} {round(v['on_seconds'] / 60)} min" for k, v in rt.items()))
        else:
            parts.append("Not enough history in the last 24 hours to describe changes.")
    if re.search(r"\bwhy\b.*\b(heater|fan|humidifier)\b|\b(heater|fan|humidifier)\b.*\b(running|on|off)\b", q):
        actuator = next((a for a in ("heater", "fan", "humidifier") if a in q), "heater")
        ctl = ctx.get("control", {})
        e = ctl.get("actuators", {}).get(actuator, {})
        state = "ON" if e.get("confirmed") else ("OFF" if e.get("confirmed") is False else "unknown")
        parts.append(f"**{actuator.capitalize()}** confirmed state: **{state}** (status {e.get('status')}, since {_dt(e.get('since'))}). "
                     f"Control mode: {ctl.get('mode')}.")
        if e.get("last_reason"):
            parts.append(f"Last control decision ({e.get('last_origin')}): {e['last_reason']}")
        else:
            parts.append("No command has been issued by the control service for this actuator; the state is reported by the device.")
        if ctl.get("interlocks"):
            parts.append(f"Active interlocks: {', '.join(ctl['interlocks'])}.")
    if re.search(r"\b(stage|phase|progress|harvest|milestone)\b", q):
        est = ctx.get("stage_estimate")
        b = ctx.get("batch")
        if b and est and est.get("available"):
            cs = est["current_stage"]
            parts.append(f"Batch **{b['code']}** ({b['species']}) is in **{cs['name']}** – grower-confirmed on {_dt(cs['started_at'])} (day {cs['elapsed_days']}).")
            parts.append(f"_Model estimate (calendar-based, confidence {est['confidence']['level']}):_ {est['timing_label']}")
            if est.get("next_stage"):
                ns = est["next_stage"]
                parts.append(f"Next milestone: **{ns['name']}**, expected between {_dt(ns['expected_window']['earliest'])} and {_dt(ns['expected_window']['latest'])}. "
                             f"Signs to look for: {', '.join(ns.get('observable_signs') or []) or 'see profile'}.")
            if est.get("harvest_window"):
                parts.append(f"Harvest window estimate: {_dt(est['harvest_window']['earliest'])} – {_dt(est['harvest_window']['latest'])} ({est['harvest_window']['basis']})")
        elif b:
            parts.append(f"Batch {b['code']} has no stage estimate: {(est or {}).get('limitation', 'no data')}")
        else:
            parts.append("No active batch is assigned to this device, so there is no stage to report.")
    if re.search(r"\b(monitor next|watch|should i monitor|investigate|before the next)\b", q):
        recs = ctx.get("recommendations", {}).get("items", [])
        if recs:
            parts.append("**Rule-based recommendations:**")
            parts.extend(f"- **{r['title']}** – {r['detected']} → {r['action']} _(confidence {r['confidence']}{'; requires confirmation' if r['requires_confirmation'] else ''})_" for r in recs)
        else:
            parts.append("No recommendations are active right now.")
    if re.search(r"\b(problem|issue|alert|anomal|wrong|error)\b", q):
        items = ctx.get("alerts", {}).get("items", [])
        an = ctx.get("anomalies", {}).get("items", [])
        if items:
            parts.append("**Alerts in the last 24 h (rule-based):**")
            parts.extend(f"- [{a['severity']}/{a['status']}] {_dt(a['opened_at'])}: {a['title']} – {a['message']}" for a in items)
        else:
            parts.append("No alerts were raised in the last 24 hours.")
        if an:
            parts.append("**Detected anomalies:**")
            parts.extend(f"- {a['label']} ({_dt(a['start'])} → {_dt(a['end'])})" for a in an)
    if re.search(r"\b(missing|gap|data quality|stale|disconnect)\b", q):
        h = ctx.get("history", {})
        gaps = h.get("missing_intervals") or []
        parts.append(f"Data completeness over the last 24 h: **{round((h.get('data_completeness') or 0) * 100, 1)} %** ({h.get('n_readings', 0)} readings).")
        if gaps:
            parts.extend(f"- gap {_dt(g['start'])} → {_dt(g['end'])} ({round(g['seconds'] / 60)} min{' – ongoing' if g.get('ongoing') else ''})" for g in gaps)
        else:
            parts.append("No telemetry gaps detected.")
        if cr and cr.get("quality"):
            bad = {k: v for k, v in cr["quality"].items() if v not in ("ok", None)}
            if bad:
                parts.append(f"Latest reading quality flags: {bad}")
        if not ctx.get("batch"):
            parts.append("Missing: no active batch is assigned to this device.")
        elif not ctx.get("observations", {}).get("items"):
            parts.append("Missing: no grower observations recorded for the batch.")
    if not parts:
        parts.append("I can tell you how the chamber is doing, the current temperature and humidity, what changed in the last 24 hours, "
                     "why the heater, fan or humidifier is on, which growth stage the batch is in, open alerts, missing data and what to do next. "
                     "Try asking: *How is my chamber doing?*")
        if cr:
            parts.append(f"{_reading_header(ctx)}: {cr['temperature_c']} °C, {cr['relative_humidity_percent']} % RH, moisture {cr['substrate_moisture_raw']} raw.")
    parts.append("")
    parts.append(FALLBACK_LABEL)
    return "\n\n".join(parts)
